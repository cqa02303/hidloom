def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def write_bytes(path: Path, data: bytes, mode: int = 0o644) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(data)
    path.chmod(mode)


def write_text(path: Path, value: str, mode: int = 0o644) -> None:
    write_bytes(path, value.encode(), mode)


def write_json(path: Path, payload: object, mode: int = 0o644) -> bytes:
    data = (json.dumps(payload, indent=2, sort_keys=True) + "\n").encode()
    write_bytes(path, data, mode)
    return data


def identity_env_bytes(identity: dict[str, str] = IDENTITY) -> bytes:
    lines = ["# Generated by rpi_os_early_initramfs.py; do not edit."]
    for key in sorted(identity):
        lines.append(f"{key}='{identity[key]}'")
        lines.append(f"export {key}")
    return ("\n".join(lines) + "\n").encode()


def dpkg_architecture() -> str:
    machine = platform.machine().lower()
    if machine in {"x86_64", "amd64"}:
        return "amd64"
    if machine in {"aarch64", "arm64"}:
        return "arm64"
    return machine


