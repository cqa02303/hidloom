def _direct_verify_with_ep0_change(
    fixture: Fixture,
    next_value: str | None,
    *,
    change_static_entry: bool = False,
) -> tuple[int, str | None]:
    """Change EP0 after its first validated snapshot inside one verification."""
    accepted = json.loads(fixture.accepted.read_text(encoding="utf-8"))
    gadget_contract = accepted["adopt"]["gadget"]
    original_validate = ADOPT.validate_ep0_max_packet_size
    calls = 0

    def validate_then_change(gadget: Path) -> int:
        nonlocal calls
        value = original_validate(gadget)
        calls += 1
        if calls == 1:
            path = gadget / "bMaxPacketSize0"
            if next_value is None:
                path.unlink()
            else:
                write_text(path, next_value)
            if change_static_entry:
                write_text(gadget / "bcdUSB", "0x0300")
        return value

    ADOPT.validate_ep0_max_packet_size = validate_then_change
    error: str | None = None
    try:
        ADOPT.validate_gadget_contract(
            fixture.configfs_root,
            fixture.sys_root,
            fixture.dev_root,
            gadget_contract,
            IDENTITY,
            allow_regular_dev_fixtures=True,
        )
    except ADOPT.AdoptError as exc:
        error = str(exc)
    finally:
        ADOPT.validate_ep0_max_packet_size = original_validate
    return calls, error


def _rewrite_e1_runtime_contract(
    fixture: Fixture,
    payload: dict[str, object],
) -> None:
    runtime = payload["runtime_contract"]
    assert isinstance(runtime, dict)
    content = {key: value for key, value in runtime.items() if key != "sha256"}
    runtime_bytes = (json.dumps(content, indent=2, sort_keys=True) + "\n").encode()
    runtime_sha = sha256(runtime_bytes)
    runtime["sha256"] = runtime_sha
    overlay = payload["overlay"]
    assert isinstance(overlay, dict)
    files = overlay["files"]
    assert isinstance(files, list)
    contract_item = next(
        item
        for item in files
        if isinstance(item, dict)
        and item.get("path") == "conf/hidloom-early-contract.json"
    )
    contract_item["size"] = len(runtime_bytes)
    contract_item["sha256"] = runtime_sha
    write_json(fixture.input_manifest, payload, 0o600)


